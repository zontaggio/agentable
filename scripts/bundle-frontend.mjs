#!/usr/bin/env node

import { promises as fs } from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const FRONTEND_DIR = path.join(ROOT, 'src', 'web', 'frontend');
const OUTPUT_FILE = path.join(ROOT, 'src', 'web', 'templates-generated.ts');

async function readFrontendAsset(fileName) {
  const abs = path.join(FRONTEND_DIR, fileName);
  return fs.readFile(abs, 'utf8');
}

async function main() {
  const [indexHtml, appCss, appJs] = await Promise.all([
    readFrontendAsset('index.html'),
    readFrontendAsset('app.css'),
    readFrontendAsset('app.js'),
  ]);

  const output = [
    '// This file is generated by scripts/bundle-frontend.mjs',
    '// Do not edit manually; update files in src/web/frontend/ instead.',
    '',
    `export const INDEX_HTML = ${JSON.stringify(indexHtml)};`,
    `export const APP_CSS = ${JSON.stringify(appCss)};`,
    `export const APP_JS = ${JSON.stringify(appJs)};`,
    '',
  ].join('\n');

  let previous = '';
  try {
    previous = await fs.readFile(OUTPUT_FILE, 'utf8');
  } catch {
    // file not found yet
  }

  if (previous === output) {
    return;
  }

  await fs.writeFile(OUTPUT_FILE, output, 'utf8');
}

main().catch((error) => {
  console.error(
    `bundle-frontend failed: ${error instanceof Error ? error.message : String(error)}`,
  );
  process.exit(1);
});
